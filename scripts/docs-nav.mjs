// Stamps the shared chrome into the /design pages.
//
//   node scripts/docs-nav.mjs --write   insert or refresh the chrome in each page
//   node scripts/docs-nav.mjs --check   fail if any page is out of date
//
// Every page gets <body class="docs"> (the page shell, see layout.css) and the
// navigation, between the docs-nav markers just inside <body>. A page with
// `index: true` also lists the other pages with their descriptions between the
// docs-index markers; place those markers by hand where the list goes.
//
// Everything outside the markers is hand-written.
//
// To add a page: add it to PAGES, create its index.html (linking
// /design/assets/layout.css), then run `npm run nav:build`.

import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";

const PAGES = [
  {
    href: "/design/",
    label: "Overview",
    description: "installation and usage",
    file: "design/index.html",
    index: true,
  },
  {
    href: "/design/reference/",
    label: "Reference",
    description: "tokens, typography and components",
    file: "design/reference/index.html",
  },
  {
    href: "/design/elements/",
    label: "Elements",
    description: "the baseline applied to every HTML element",
    file: "design/elements/index.html",
  },
  {
    href: "/design/license/",
    label: "License",
    description: "terms of use (draft)",
    file: "design/license/index.html",
  },
];

const marks = (name) => [
  name,
  `<!-- ${name}:start (generated by scripts/docs-nav.mjs) -->`,
  `<!-- ${name}:end -->`,
];
const NAV = marks("docs-nav");
const INDEX = marks("docs-index");
const LAYOUT_CSS = "/design/assets/layout.css";
const BODY_TAG = /<body([^>]*)>/;

const renderNav = (current) => {
  const items = PAGES.map(({ href, label }) => {
    const aria = href === current ? ' aria-current="page"' : "";
    return `<li><a href="${href}"${aria}>${label}</a></li>`;
  });
  return [
    '<nav class="docs-nav" aria-label="Design system">',
    '<span class="docs-nav-title">Handcrafted Design</span>',
    "<ul>",
    ...items,
    "</ul>",
    "</nav>",
  ].join("\n");
};

const renderIndex = (current) => {
  const items = PAGES.filter(({ href }) => href !== current).map(
    ({ href, label, description }) =>
      `<li><a href="${href}">${label}</a> - ${description}</li>`,
  );
  return [
    '<nav class="docs-index" aria-label="More in the design system">',
    "<ul>",
    ...items,
    "</ul>",
    "</nav>",
  ].join("\n");
};

// Adds "docs" to <body class="...">, keeping any classes already there.
const withDocsClass = (tag, attrs) => {
  const existing = /class="([^"]*)"/.exec(attrs);
  if (!existing) return `<body class="docs"${attrs}>`;
  if (existing[1].split(/\s+/).includes("docs")) return tag;
  return `<body${attrs.replace(existing[0], `class="docs ${existing[1]}"`)}>`;
};

// Replaces what sits between a pair of markers.
const fill = (page, [name, start, end], html) => {
  const from = page.indexOf(start);
  const to = page.indexOf(end);
  if (from === -1 || to < from) throw new Error(`missing ${name} markers`);
  return `${page.slice(0, from + start.length)}\n${html}\n${page.slice(to)}`;
};

// Returns the page with its chrome stamped in. Safe to run repeatedly.
const stamp = (page, { href, index }) => {
  if (!page.includes(LAYOUT_CSS)) {
    throw new Error(`missing the ${LAYOUT_CSS} stylesheet link`);
  }
  if (!BODY_TAG.test(page)) throw new Error("no <body> tag");
  if (page.includes("docs-content")) {
    throw new Error(
      "remove the old docs-content wrapper; it is no longer used",
    );
  }

  let next = page.replace(BODY_TAG, withDocsClass);
  const [, navStart, navEnd] = NAV;
  if (!next.includes(navStart) && !next.includes(navEnd)) {
    next = next.replace(BODY_TAG, (tag) => `${tag}\n${navStart}\n${navEnd}`);
  }
  next = fill(next, NAV, renderNav(href));
  if (index) next = fill(next, INDEX, renderIndex(href));
  return next;
};

// Whitespace is the only thing Prettier changes, so compare without it.
const squash = (html) =>
  html
    .replace(/\s+/g, " ")
    .replace(/\s*(<[^>]+>)\s*/g, "$1")
    .trim();

const mode = process.argv[2];
if (mode !== "--write" && mode !== "--check") {
  throw new Error("Usage: docs-nav.mjs --write | --check");
}

const problems = [];
for (const entry of PAGES) {
  const page = readFileSync(entry.file, "utf8");
  try {
    const next = stamp(page, entry);
    if (mode === "--write") {
      if (next !== page) writeFileSync(entry.file, next);
    } else if (squash(next) !== squash(page)) {
      problems.push(`${entry.file}: out of date`);
    }
  } catch (error) {
    problems.push(`${entry.file}: ${error.message}`);
  }
}

if (problems.length > 0) {
  throw new Error(`${problems.join("\n")}\nThen run: npm run nav:build`);
}
